import { test, expect } from "@playwright/test";
test("case ownership, notes and risk dismissal survive reload", async ({ page }) => {
  await page.goto("/#risk-radar");
  await page.getByRole("button", { name: "Investigate", exact: true }).first().click();
  await page.getByRole("tab", { name: "Review", exact: true }).click();
  await expect(page.getByLabel("Case status")).toBeEnabled();
  await page.getByLabel("Case status").selectOption("Monitoring");
  await page.getByLabel("Case owner").selectOption("local-analyst");
  await page.getByLabel("Case note").fill("Evidence reviewed; monitor the next snapshot.");
  await page.getByRole("button", { name: "Save case update" }).click();
  await expect(page.locator(".case-events")).toContainText("Evidence reviewed");
  await page.reload();
  await expect(page.getByLabel("Case status")).toHaveValue("Monitoring");
  await expect(page.locator(".case-events")).toContainText("Evidence reviewed");
  await page.goto("/#risk-radar");
  await page.getByRole("button", { name: "Dismiss", exact: true }).first().click();
  await expect(page.getByRole("status")).toContainText("Risk dismissal saved");
  await page.reload();
  await expect(page.locator(".risk-grid .risk-card")).toHaveCount(3);
  await page.getByRole("button", { name: "Restore dismissed" }).click();
  await expect(page.getByRole("status")).toContainText("Risk signals reopened");
  await expect(page.locator(".risk-grid .risk-card")).toHaveCount(4);
});
